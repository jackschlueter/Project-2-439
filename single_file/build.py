"""Merge the app into one self-contained single_file/app.py. Run: python single_file/build.py"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_FILES = ("prices.csv", "dgs10_2026-10-31.csv", "dgs10_2026-11-03.csv", "dgs10-data-card.md")
MODULES = ("portfolio_engine.py", "pit_signal.py", "lab13_mandate.py", "app.py")
LOCAL_IMPORTS = ("from portfolio_engine import", "from pit_signal import", "from lab13_mandate import")
SWAPS = (
    ('ROOT / "dgs10_2026-10-31.csv"', '"dgs10_2026-10-31.csv"'),
    ('ROOT / "dgs10_2026-11-03.csv"', '"dgs10_2026-11-03.csv"'),
    ('VINTAGES[selected].read_text(encoding="utf-8-sig")', 'DATA[VINTAGES[selected]]'),
    ('VINTAGES[vintage].read_text(encoding="utf-8-sig")', 'DATA[VINTAGES[vintage]]'),
    ('file_name=VINTAGES[selected].name', 'file_name=VINTAGES[selected]'),
    ('(ROOT / "dgs10-data-card.md").read_bytes()', 'DATA["dgs10-data-card.md"].encode()'),
    ('read_prices(ROOT / "prices.csv")', 'read_prices(DATA["prices.csv"].encode())'),
)


def main():
    parts = ['"""Meridian Portfolio Committee: single-file version, generated by single_file/build.py.\n\n'
             'Run: pip install numpy pandas streamlit, then: python -m streamlit run app.py\n"""\n',
             "DATA = {\n" + "".join(
                 f"    {name!r}: {(ROOT / name).read_text(encoding='utf-8-sig')!r},\n" for name in DATA_FILES
             ) + "}\n"]
    for module in MODULES:
        code = (ROOT / module).read_text(encoding="utf-8")
        lines = []
        skipping = False
        for line in code.splitlines():
            if line.startswith(LOCAL_IMPORTS):
                skipping = line.rstrip().endswith("(")
                continue
            if skipping:
                skipping = not line.rstrip().endswith(")")
                continue
            lines.append(line)
        code = "\n".join(lines) + "\n"
        for old, new in SWAPS:
            code = code.replace(old, new)
        parts.append(f"\n# ===== {module} =====\n{code}")
    text = "".join(parts)
    for old, _ in SWAPS:
        if old in text:
            raise RuntimeError(f"Unreplaced file read: {old}")
    (ROOT / "single_file" / "app.py").write_text(text, encoding="utf-8")
    print(f"Wrote single_file/app.py ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
